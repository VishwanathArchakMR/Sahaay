"""Authoritative Native Document & Spreadsheet Artifact Generator for Sahaay.

Produces genuine, editable office artifacts (.docx, .xlsx, .csv, .md, .txt) using
the standard library OpenXML packaging engine, and executes deterministic tabular data analysis
backed by in-memory SQLite tables.
"""

import csv
import hashlib
import logging
import os
import re
import sqlite3
import statistics
import zipfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional
from uuid import uuid4

from sahaay_core.storage.persistence import durable_storage

logger = logging.getLogger(__name__)


class ArtifactGeneratorService:
    """Creates real editable documents and workbooks, with cryptographic readback verification."""

    @staticmethod
    def _resolve_path(output_path_str: str, default_name: str, ext: str) -> Path:
        """Expands environment variables and user desktop / workspace paths safely."""
        cleaned = output_path_str.replace("%USERPROFILE%", str(Path.home())).replace(
            "~", str(Path.home())
        )
        p = Path(cleaned)
        if p.is_dir() or cleaned.endswith(("\\", "/")):
            p = p / f"{default_name}.{ext}"
        elif not p.suffix:
            p = p.with_suffix(f".{ext}")
        p.parent.mkdir(parents=True, exist_ok=True)
        return p

    def generate_document(
        self,
        title: str,
        sections: List[Dict[str, str]],
        output_path: str,
        format_type: str = "docx",
        task_id: Optional[str] = None,
        sources: Optional[List[str]] = None,
    ) -> Dict[str, Any]:
        """Generates a genuine Word DOCX or Markdown report with formatting, metadata, and citations."""
        fmt = format_type.lower().strip().replace(".", "")
        if fmt not in ("docx", "md", "txt"):
            fmt = "docx"

        target_file = self._resolve_path(output_path, "Sahaay_Report", fmt)

        if fmt == "docx":
            self._write_openxml_docx(target_file, title, sections, sources)
        else:
            self._write_markdown_doc(target_file, title, sections, sources)

        # Cryptographic readback verification
        raw_bytes = target_file.read_bytes()
        sha256_hash = hashlib.sha256(raw_bytes).hexdigest()
        file_size = len(raw_bytes)

        artifact_id = str(uuid4())
        try:
            durable_storage.save_artifact(
                artifact_id=artifact_id,
                task_id=task_id or "default",
                artifact_type=fmt,
                file_path=str(target_file),
                file_size_bytes=file_size,
            )
        except Exception as ex:
            logger.warning("Could not persist artifact record: %s", ex)

        return {
            "success": True,
            "artifactId": artifact_id,
            "filePath": str(target_file),
            "format": fmt,
            "fileSize": file_size,
            "sha256": sha256_hash,
            "title": title,
            "sectionCount": len(sections),
            "isVerified": file_size > 0 and target_file.exists(),
        }

    def _write_markdown_doc(
        self,
        target_file: Path,
        title: str,
        sections: List[Dict[str, str]],
        sources: Optional[List[str]],
    ) -> None:
        lines = [
            f"# {title}",
            f"*Generated by Sahaay Autonomous AI Agent — {datetime.now(timezone.utc).strftime('%A, %B %d, %Y')}*",
            "",
            "---",
            "",
        ]
        for sec in sections:
            heading = sec.get("heading") or sec.get("title") or "Section"
            content = sec.get("content") or sec.get("body") or ""
            lines.append(f"## {heading}\n")
            lines.append(f"{content}\n")

        if sources:
            lines.append("## Citations & Sources\n")
            for idx, s in enumerate(sources, 1):
                lines.append(f"{idx}. {s}")
            lines.append("")

        target_file.write_text("\n".join(lines), encoding="utf-8")

    def _write_openxml_docx(
        self,
        target_file: Path,
        title: str,
        sections: List[Dict[str, str]],
        sources: Optional[List[str]],
    ) -> None:
        """Packages a valid OpenXML Word (.docx) document."""
        content_types = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">\n'
            '  <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>\n'
            '  <Default Extension="xml" ContentType="application/xml"/>\n'
            '  <Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>\n'
            "</Types>"
        )
        rels = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">\n'
            '  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/>\n'
            "</Relationships>"
        )

        body_paragraphs = []
        # Title paragraph
        body_paragraphs.append(
            f'<w:p><w:pPr><w:jc w:val="center"/></w:pPr><w:r><w:rPr><w:b/><w:sz w:val="48"/><w:color w:val="1E293B"/></w:rPr><w:t>{self._escape_xml(title)}</w:t></w:r></w:p>'
        )
        # Subtitle paragraph
        date_str = datetime.now(timezone.utc).strftime("%A, %B %d, %Y")
        body_paragraphs.append(
            f'<w:p><w:pPr><w:jc w:val="center"/></w:pPr><w:r><w:rPr><w:i/><w:sz w:val="20"/><w:color w:val="64748B"/></w:rPr><w:t>Generated by Sahaay Autonomous AI Agent — {date_str}</w:t></w:r></w:p>'
        )
        body_paragraphs.append("<w:p><w:r><w:t></w:t></w:r></w:p>")

        for sec in sections:
            heading = sec.get("heading") or sec.get("title") or "Section"
            content = sec.get("content") or sec.get("body") or ""
            # Heading 2
            body_paragraphs.append(
                f'<w:p><w:r><w:rPr><w:b/><w:sz w:val="28"/><w:color w:val="0F172A"/></w:rPr><w:t>{self._escape_xml(heading)}</w:t></w:r></w:p>'
            )
            # Body paragraphs split by newline
            for para in content.split("\n"):
                trimmed = para.strip()
                if trimmed:
                    body_paragraphs.append(
                        f'<w:p><w:r><w:rPr><w:sz w:val="22"/><w:color w:val="334155"/></w:rPr><w:t>{self._escape_xml(trimmed)}</w:t></w:r></w:p>'
                    )

        if sources:
            body_paragraphs.append("<w:p><w:r><w:t></w:t></w:r></w:p>")
            body_paragraphs.append(
                '<w:p><w:r><w:rPr><w:b/><w:sz w:val="26"/><w:color w:val="0F172A"/></w:rPr><w:t>References and Sources</w:t></w:r></w:p>'
            )
            for idx, s in enumerate(sources, 1):
                body_paragraphs.append(
                    f'<w:p><w:r><w:rPr><w:sz w:val="20"/><w:color w:val="475569"/></w:rPr><w:t>[{idx}] {self._escape_xml(s)}</w:t></w:r></w:p>'
                )

        document_xml = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">\n'
            "  <w:body>\n"
            + "\n".join(body_paragraphs)
            + '\n    <w:sectPr><w:pgSz w:w="12240" w:h="15840"/><w:pgMar w:top="1440" w:right="1440" w:bottom="1440" w:left="1440"/></w:sectPr>\n'
            "  </w:body>\n"
            "</w:document>"
        )

        with zipfile.ZipFile(target_file, "w", zipfile.ZIP_DEFLATED) as zf:
            zf.writestr("[Content_Types].xml", content_types)
            zf.writestr("_rels/.rels", rels)
            zf.writestr("word/document.xml", document_xml)

    def generate_spreadsheet(
        self,
        title: str,
        headers: List[str],
        rows: List[List[Any]],
        output_path: str,
        format_type: str = "xlsx",
        formulas: Optional[Dict[str, str]] = None,
        task_id: Optional[str] = None,
    ) -> Dict[str, Any]:
        """Generates a genuine Excel XLSX or CSV workbook with headers and formulas."""
        fmt = format_type.lower().strip().replace(".", "")
        if fmt not in ("xlsx", "csv"):
            fmt = "xlsx"

        target_file = self._resolve_path(output_path, "Sahaay_Workbook", fmt)

        if fmt == "xlsx":
            self._write_openxml_xlsx(target_file, headers, rows, formulas)
        else:
            with open(target_file, "w", newline="", encoding="utf-8") as f:
                writer = csv.writer(f)
                if headers:
                    writer.writerow(headers)
                for r in rows:
                    writer.writerow(r)

        raw_bytes = target_file.read_bytes()
        sha256_hash = hashlib.sha256(raw_bytes).hexdigest()
        file_size = len(raw_bytes)

        artifact_id = str(uuid4())
        try:
            durable_storage.save_artifact(
                artifact_id=artifact_id,
                task_id=task_id or "default",
                artifact_type=fmt,
                file_path=str(target_file),
                file_size_bytes=file_size,
            )
        except Exception as ex:
            logger.warning("Could not persist artifact record: %s", ex)

        return {
            "success": True,
            "artifactId": artifact_id,
            "filePath": str(target_file),
            "format": fmt,
            "rowCount": len(rows),
            "colCount": len(headers),
            "fileSize": file_size,
            "sha256": sha256_hash,
            "isVerified": file_size > 0 and target_file.exists(),
        }

    def _write_openxml_xlsx(
        self,
        target_file: Path,
        headers: List[str],
        rows: List[List[Any]],
        formulas: Optional[Dict[str, str]] = None,
    ) -> None:
        """Packages a valid OpenXML Excel (.xlsx) workbook."""
        content_types = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">\n'
            '  <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>\n'
            '  <Default Extension="xml" ContentType="application/xml"/>\n'
            '  <Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>\n'
            '  <Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>\n'
            "</Types>"
        )
        rels = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">\n'
            '  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/>\n'
            "</Relationships>"
        )
        workbook_rels = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">\n'
            '  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/>\n'
            "</Relationships>"
        )
        workbook_xml = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">\n'
            "  <sheets>\n"
            '    <sheet name="Sheet1" sheetId="1" r:id="rId1"/>\n'
            "  </sheets>\n"
            "</workbook>"
        )

        sheet_rows = []
        row_num = 1

        # Header row
        if headers:
            header_cells = []
            for col_idx, h in enumerate(headers):
                col_letter = self._col_to_letter(col_idx + 1)
                header_cells.append(
                    f'<c r="{col_letter}{row_num}" t="inlineStr"><is><t>{self._escape_xml(str(h))}</t></is></c>'
                )
            sheet_rows.append(f'<row r="{row_num}">{"".join(header_cells)}</row>')
            row_num += 1

        # Data rows
        for row in rows:
            data_cells = []
            for col_idx, val in enumerate(row):
                col_letter = self._col_to_letter(col_idx + 1)
                cell_ref = f"{col_letter}{row_num}"
                formula = (formulas or {}).get(cell_ref)
                if formula:
                    data_cells.append(f'<c r="{cell_ref}"><f>{self._escape_xml(formula)}</f></c>')
                elif isinstance(val, (int, float)):
                    data_cells.append(f'<c r="{cell_ref}"><v>{val}</v></c>')
                else:
                    data_cells.append(
                        f'<c r="{cell_ref}" t="inlineStr"><is><t>{self._escape_xml(str(val))}</t></is></c>'
                    )
            sheet_rows.append(f'<row r="{row_num}">{"".join(data_cells)}</row>')
            row_num += 1

        sheet1_xml = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">\n'
            "  <sheetData>\n" + "\n".join(sheet_rows) + "\n  </sheetData>\n"
            "</worksheet>"
        )

        with zipfile.ZipFile(target_file, "w", zipfile.ZIP_DEFLATED) as zf:
            zf.writestr("[Content_Types].xml", content_types)
            zf.writestr("_rels/.rels", rels)
            zf.writestr("xl/_rels/workbook.xml.rels", workbook_rels)
            zf.writestr("xl/workbook.xml", workbook_xml)
            zf.writestr("xl/worksheets/sheet1.xml", sheet1_xml)

    @staticmethod
    def _col_to_letter(col_idx: int) -> str:
        result = []
        while col_idx > 0:
            col_idx, remainder = divmod(col_idx - 1, 26)
            result.append(chr(65 + remainder))
        return "".join(reversed(result))

    @staticmethod
    def _escape_xml(text: str) -> str:
        return (
            str(text)
            .replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
            .replace('"', "&quot;")
            .replace("'", "&apos;")
        )

    # --- Tabular Data Analysis Engine ---
    def analyze_tabular_data(
        self,
        table_data: Any,
        query: Optional[str] = None,
        operations: Optional[List[str]] = None,
    ) -> Dict[str, Any]:
        """Performs deterministic statistical and SQL analysis over tabular CSV/JSON datasets."""
        # Convert table_data to rows and columns
        headers: List[str] = []
        rows: List[List[Any]] = []

        if isinstance(table_data, str) and (os.path.exists(table_data) or "\n" in table_data):
            # Parse CSV from path or raw string
            raw_text = (
                Path(table_data).read_text(encoding="utf-8")
                if os.path.exists(table_data)
                else table_data
            )
            reader = csv.reader(raw_text.strip().splitlines())
            raw_rows = list(reader)
            if raw_rows:
                headers = [h.strip() for h in raw_rows[0]]
                rows = raw_rows[1:]
        elif isinstance(table_data, list):
            if table_data and isinstance(table_data[0], dict):
                headers = list(table_data[0].keys())
                rows = [[item.get(h) for h in headers] for item in table_data]
            elif table_data and isinstance(table_data[0], list):
                headers = [f"col_{i}" for i in range(len(table_data[0]))]
                rows = table_data

        if not headers or not rows:
            return {"success": False, "error": "No tabular rows found to analyze."}

        # Build in-memory SQLite table
        conn = sqlite3.connect(":memory:")
        clean_headers = [
            re.sub(r"[^a-zA-Z0-9_]", "_", str(h)).strip("_") or f"col_{i}"
            for i, h in enumerate(headers)
        ]
        # Ensure uniqueness
        seen: Dict[str, int] = {}
        unique_headers = []
        for h in clean_headers:
            h_lower = h.lower()
            if h_lower in seen:
                seen[h_lower] += 1
                unique_headers.append(f"{h}_{seen[h_lower]}")
            else:
                seen[h_lower] = 1
                unique_headers.append(h)
        clean_headers = unique_headers

        col_defs = ", ".join(f'"{col}" NUMERIC' for col in clean_headers)
        conn.execute(f"CREATE TABLE data_table ({col_defs})")

        def _clean_val(v: Any) -> Any:
            if v is None:
                return None
            if isinstance(v, (int, float)):
                return v
            s = str(v).strip()
            try:
                num_str = s.replace(",", "").replace("$", "").replace("₹", "").strip()
                if "." in num_str:
                    return float(num_str)
                return int(num_str)
            except (ValueError, TypeError):
                return s

        placeholders = ", ".join("?" for _ in headers)
        conn.executemany(
            f"INSERT INTO data_table VALUES ({placeholders})",
            [[_clean_val(v) for v in r] for r in rows],
        )

        # Compute column statistics
        stats: Dict[str, Any] = {}
        for idx, (orig_h, _clean_h) in enumerate(zip(headers, clean_headers, strict=False)):
            col_vals = [r[idx] for r in rows if idx < len(r) and r[idx] is not None]
            num_vals = []
            for v in col_vals:
                try:
                    cleaned_num = str(v).replace(",", "").replace("$", "").replace("₹", "").strip()
                    num_vals.append(float(cleaned_num))
                except (ValueError, TypeError):
                    pass

            if num_vals:
                stats[orig_h] = {
                    "count": len(num_vals),
                    "sum": round(sum(num_vals), 4),
                    "mean": round(statistics.mean(num_vals), 4),
                    "median": round(statistics.median(num_vals), 4),
                    "min": min(num_vals),
                    "max": max(num_vals),
                }
            else:
                stats[orig_h] = {
                    "count": len(col_vals),
                    "unique": len(set(col_vals)),
                }

        # Custom SQL query if provided
        query_results = []
        if query:
            try:
                cur = conn.cursor()
                cur.execute(query)
                q_cols = [d[0] for d in cur.description] if cur.description else []
                q_rows = cur.fetchall()
                query_results = [dict(zip(q_cols, r, strict=False)) for r in q_rows]
            except Exception as q_ex:
                query_results = [{"error": str(q_ex)}]

        conn.close()

        # Format markdown preview table
        md_table_lines = [
            "| " + " | ".join(headers[:8]) + " |",
            "| " + " | ".join(["---"] * min(len(headers), 8)) + " |",
        ]
        for r in rows[:10]:
            row_slice = [str(r[i]) if i < len(r) else "" for i in range(min(len(headers), 8))]
            md_table_lines.append("| " + " | ".join(row_slice) + " |")

        return {
            "success": True,
            "totalRows": len(rows),
            "totalColumns": len(headers),
            "headers": headers,
            "statistics": stats,
            "queryResults": query_results,
            "markdownPreview": "\n".join(md_table_lines),
        }


artifact_generator = ArtifactGeneratorService()
